#!/usr/bin/env python3
"""
Plot side-by-side OT vs MW predictor summary.

Input summaries are generated by round1_predictors_to_outcomes_analysis.py.
Each panel shows Spearman ρ for the same participant-level real-data
predictors against one real-vs-fake outcome.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
import numpy as np
import pandas as pd

from round1_predictors_to_outcomes_analysis import pretty_name, predictor_category_extended
from round1_all_predictors_correlation import CATEGORY_COLOR, significance_stars


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent

DEFAULT_OT_SUMMARY = PROJECT_ROOT / "results" / "round1_predictors_to_outcomes" / "predictor_to_outcome_correlation_summary.csv"
DEFAULT_MW_SUMMARY = PROJECT_ROOT / "mw_pipeline" / "results" / "round1_predictors_to_outcomes" / "predictor_to_outcome_correlation_summary.csv"
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "results" / "ot_mw_predictor_summary_compare"


def load_outcome(path: Path, outcome: str, label: str) -> pd.DataFrame:
    df = pd.read_csv(path)
    if outcome not in set(df["outcome"]):
        raise ValueError(f"{label} summary lacks outcome '{outcome}': {path}")
    out = df[df["outcome"] == outcome].copy()
    out["task"] = label
    out["abs_spearman_rho"] = out["spearman_rho"].abs()
    return out


def common_predictor_order(ot: pd.DataFrame, mw: pd.DataFrame, sort_by: str = "mean_abs") -> List[str]:
    merged = ot[["predictor", "abs_spearman_rho"]].merge(
        mw[["predictor", "abs_spearman_rho"]],
        on="predictor",
        suffixes=("_ot", "_mw"),
    )
    merged["max_abs_rho"] = merged[["abs_spearman_rho_ot", "abs_spearman_rho_mw"]].max(axis=1)
    merged["mean_abs_rho"] = merged[["abs_spearman_rho_ot", "abs_spearman_rho_mw"]].mean(axis=1)
    sort_col = "mean_abs_rho" if sort_by == "mean_abs" else "max_abs_rho"
    return merged.sort_values(sort_col, ascending=False)["predictor"].tolist()


def make_panel(ax, df: pd.DataFrame, predictor_order: List[str], title: str) -> None:
    indexed = df.set_index("predictor")
    y = np.arange(len(predictor_order))
    rho = np.array([indexed.loc[p, "spearman_rho"] for p in predictor_order], dtype=float)
    q = np.array([indexed.loc[p, "spearman_p_value_fdr_bh"] for p in predictor_order], dtype=float)
    colors = [
        CATEGORY_COLOR.get(predictor_category_extended(p), "#455a64")
        for p in predictor_order
    ]

    for yi, ri, color in zip(y, rho, colors):
        ax.hlines(yi, 0, ri, color=color, linewidth=2.0, alpha=0.85)
    ax.scatter(rho, y, s=34, color=colors, edgecolors="white", linewidths=0.6, zorder=3)

    for yi, ri, qv in zip(y, rho, q):
        dx = 0.018 if ri >= 0 else -0.018
        ha = "left" if ri >= 0 else "right"
        ax.text(ri + dx, yi, f"{ri:.2f}{significance_stars(qv)}", va="center", ha=ha, fontsize=8.5)

    ax.axvline(0, color="black", linewidth=0.8)
    ax.set_title(title, loc="left", fontsize=13, fontweight="bold")
    ax.set_xlim(-1.15, 1.15)
    ax.set_xticks(np.linspace(-1.0, 1.0, 5))
    ax.grid(axis="x", linestyle="--", alpha=0.25)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def plot_compare(ot: pd.DataFrame, mw: pd.DataFrame, outcome: str, output_path: Path, sort_by: str) -> None:
    predictor_order = common_predictor_order(ot, mw, sort_by=sort_by)
    labels = [pretty_name(p) for p in predictor_order]

    plt.rcParams["font.family"] = "Arial"
    plt.rcParams["font.size"] = 10
    plt.rcParams["axes.labelsize"] = 12
    plt.rcParams["xtick.labelsize"] = 10
    plt.rcParams["ytick.labelsize"] = 9.2

    height = max(6.0, 0.34 * len(predictor_order) + 1.6)
    fig, axes = plt.subplots(1, 2, figsize=(12.0, height), sharey=True, facecolor="white")
    for ax in axes:
        ax.set_facecolor("white")

    make_panel(axes[0], ot, predictor_order, "OT")
    make_panel(axes[1], mw, predictor_order, "MW")

    axes[0].set_yticks(np.arange(len(predictor_order)))
    axes[0].set_yticklabels(labels)
    axes[1].tick_params(axis="y", labelleft=False)
    axes[0].set_ylim(len(predictor_order) - 0.5, -0.5)

    xlabel = f"Spearman ρ with {pretty_name(outcome)}"
    axes[0].set_xlabel(xlabel)
    axes[1].set_xlabel(xlabel)

    fig.suptitle(f"OT vs MW Predictor Summary: {pretty_name(outcome)}", fontsize=15, fontweight="bold", y=0.995)

    categories = [predictor_category_extended(p) for p in predictor_order]
    legend_order = ["Global distance", "Time-domain", "Frequency-domain", "Complexity", "Entropy"]
    handles = [
        Line2D([0], [0], marker="o", color="none", markerfacecolor=CATEGORY_COLOR[c],
               markeredgecolor="white", markersize=7, label=c)
        for c in legend_order
        if c in set(categories)
    ]
    axes[1].legend(handles=handles, frameon=False, loc="lower right", fontsize=8.5)
    axes[0].text(
        0.28,
        0.02,
        "* FDR-p < 0.05\n** FDR-p < 0.01\n*** FDR-p < 0.001",
        transform=axes[0].transAxes,
        ha="right",
        va="bottom",
        fontsize=8.5,
    )

    plt.tight_layout(rect=[0, 0, 1, 0.97])
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=600, bbox_inches="tight")
    plt.close(fig)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot OT vs MW side-by-side predictor summaries.")
    parser.add_argument("--ot-summary", type=str, default=str(DEFAULT_OT_SUMMARY))
    parser.add_argument("--mw-summary", type=str, default=str(DEFAULT_MW_SUMMARY))
    parser.add_argument("--outcome", type=str, default="pca_overlap", choices=["pca_overlap", "SWD"])
    parser.add_argument("--output-dir", type=str, default=str(DEFAULT_OUTPUT_DIR))
    parser.add_argument(
        "--sort-by",
        choices=["mean_abs", "max_abs"],
        default="mean_abs",
        help="mean_abs ranks predictors high only when they are informative across tasks; max_abs ranks predictors high if strong in either task.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    ot_summary = Path(args.ot_summary)
    mw_summary = Path(args.mw_summary)
    out_dir = Path(args.output_dir)

    ot = load_outcome(ot_summary, args.outcome, "OT")
    mw = load_outcome(mw_summary, args.outcome, "MW")
    out_path = out_dir / f"ot_vs_mw_predictor_summary_{args.outcome}.png"
    plot_compare(ot, mw, args.outcome, out_path, sort_by=args.sort_by)
    print(f"Saved: {out_path}")


if __name__ == "__main__":
    main()
